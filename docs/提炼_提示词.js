/* 出图用的【改】/【新增】标记是给上色看的，AI 不需要，也不能被抄进结果 */
function stripMarks(s) {
  return String(s == null ? '' : s)
    .split('【改】').join('').split('【/改】').join('')
    .split('【新增】').join('').split('【/新增】').join('');
}

/* 把已勾选内容还原成「原文」版式，供 DeepSeek 阅读 */
function promptSource(sections) {
  const out = [];
  sections.forEach(sec => {
    if (sec.name) out.push(stripMarks(sec.name), '');
    sec.groups.forEach(g => {
      const gn = stripMarks(g.name || '').trim();
      if (gn) out.push('【' + gn + '】', '');
      g.items.forEach(it => {
        const t = stripMarks(it.t), d = stripMarks(it.d);
        /* 标题行统一打上 ◆ 前缀：这类行没有任何编号、也不以句号结尾，AI 容易当成
           过渡句整条删掉（实测会连小节一起消失）。打了标记就必须保留 */
        if (it.sub) {
          out.push('◆ ' + t, '');
          return;
        }
        if (t) out.push('◆ ' + t);
        if (d) out.push(d);
        out.push('');
      });
    });
  });
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}

function buildDeepSeekText() {
  const data = collect();
  const rest = splitCore(data.sections, allSecNames()).rest;
  if (!rest.length) return '';
  /* 元信息随提示词下发，要求原样回显，出图端据此自动识别服务器 / 日期 */
  const metaLine = '@@META 服务器=' + (data.server || '正式服')
    + (data.date ? ' 日期=' + data.date : '');
  /* 交给 AI 的永远只有局外章节，所以范围说明里不必再提「第一章」 */
  const scope = '【本次范围】下面提供的是本次要出图的局外章节（系统、玩法、活动、资源、问题修复这类内容）：只输出这些章节，章节标题和编号照抄原文，不要自己补章节，也不要补原文没有的分组。\n\n';
  const tail = '现在直接输出结果正文：所有章节都按上面的「挑哪些、删哪些」挑重点、轻度精简，但意思必须与原文完全一致。严格使用【输出格式】里的符号，不要任何解释、不要 Markdown。\n'
    + '最后再强调一次：章节标题照抄原文、不要自己补章节；绝对忠于原文，只删不改，数值、时间、价格、上限必须与原文一致。';
  return '【元信息】' + metaLine + '\n'
    + '上面的【元信息】必须原样放在输出结果的第一行（保留 @@META 前缀和空格），第二行开始才是正文，不要把它改写成正文条目。\n\n'
    + scope
    + DS_PROMPT
    + '\n==================== 以下为原文 ====================\n\n'
    + promptSource(rest)
    + '\n\n==================== 原文结束 ====================\n\n'
    + tail;
}

async function copyPrompt() {
  const txt = buildDeepSeekText();
  if (!txt) { setStatus('本篇只有第一章，不需要 AI；直接「复制 JSON」即可', 'err'); return; }
  const what = noCoreMode ? '整篇（没有第一章）' : '第二～五章';
  try {
    await navigator.clipboard.writeText(txt);
    setStatus(what + '提示词 + 原文已复制（' + txt.length + ' 字）', 'ok');
  } catch (e) {
    const ta = document.createElement('textarea');
    ta.value = txt; document.body.appendChild(ta); ta.select();
    document.execCommand('copy'); ta.remove();
    setStatus(what + '提示词 + 原文已复制', 'ok');
  }
}

